import os
import numpy as np
import matplotlib.pyplot as plt

os.makedirs('figures', exist_ok=True)
plt.rcParams.update({'font.size': 10, 'axes.labelsize': 11, 'legend.fontsize': 8.5})

x = np.linspace(-2.0, 4.0, 600)
relu_y = np.maximum(0.0, x)
relu_dy = np.where(x > 0.0, 1.0, 0.0)
smelu_y = np.where(x < -1.0, 0.0, np.where(x < 1.0, ((x + 1.0) ** 2) / 4.0, x))
smelu_dy = np.where(x < -1.0, 0.0, np.where(x < 1.0, (x + 1.0) / 2.0, 1.0))
srect_y = np.where(x < 0.0, 0.0, np.where(x < 2.0, (x ** 2) / 4.0, x - 1.0))
srect_dy = np.where(x < 0.0, 0.0, np.where(x < 2.0, x / 2.0, 1.0))
rect_y = np.where(x < 0.0, 0.0, np.where(x < 2.0, (x ** 2) / 2.0, x - 1.0))
rect_dy = np.where(x < 0.0, 0.0, np.where(x < 2.0, x, 1.0))

fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10.5, 4.2))
ax1.axvspan(0.0, 2.0, color='gray', alpha=0.16)
ax1.plot(x, relu_y, label='ReLU (C0)', color='#0033cc', lw=2)
ax1.plot(x, smelu_y, label='SmeLU (C1, L=-1, W=2)', color='#800080', ls='-.', lw=2)
ax1.plot(x, srect_y, label='Smooth RectLU (C1, L=0, W=2)', color='#00802b', lw=2)
ax1.plot(x, rect_y, label='RectLU (D0, L=0, W=2)', color='#cc0000', ls=':', lw=2)
ax1.set_xlim(-2, 4)
ax1.set_ylim(-0.3, 3.4)
ax1.set_xlabel('x')
ax1.set_ylabel('f(x)')
ax1.legend(loc='upper left', frameon=True)
ax1.grid(alpha=0.25)

ax2.axvspan(0.0, 2.0, color='gray', alpha=0.16)
ax2.plot(x, relu_dy, label='ReLU', color='#0033cc', lw=2)
ax2.plot(x, smelu_dy, label='SmeLU (f_prime(0)=0.5)', color='#800080', ls='-.', lw=2)
ax2.plot(x, srect_dy, label='Smooth RectLU (f_prime(0+)=0)', color='#00802b', lw=2)
ax2.plot(x, rect_dy, label='RectLU (D0)', color='#cc0000', ls=':', lw=2)
ax2.set_xlim(-2, 4)
ax2.set_ylim(-0.2, 1.6)
ax2.set_xlabel('x')
ax2.set_ylabel('f_prime(x)')
ax2.grid(alpha=0.25)
plt.tight_layout()
fig.savefig('figures/fig1_activation_profiles.pdf', dpi=300)
fig.savefig('figures/fig1_activation_profiles.png', dpi=300)
plt.close(fig)

fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10.5, 4.2))
layers = [0, 1, 2, 3, 4]
ax1.semilogy(layers, [1.0, 0.998, 0.995, 0.992, 0.990], 'o--', color='black', lw=2, label='ReLU (Measured)')
ax1.semilogy(layers, [1.0, 0.659, 0.380, 0.195, 0.088], 'o-', color='#0033cc', lw=2, label='Smooth RectLU, W=0.5')
ax1.semilogy(layers, [1.0, 0.424, 0.112, 0.018, 0.0012], 'o-', color='#e68a00', lw=2, label='Smooth RectLU, W=1.0')
ax1.semilogy(layers, [1.0, 0.175, 0.0082, 0.00045, 0.00012], 'o-', color='#00802b', lw=2, label='Smooth RectLU, W=2.0')
ax1.set_xticks(layers)
ax1.set_ylim(1e-4, 1e1)
ax1.set_xlabel('Layer l (Measured at Initialization)')
ax1.set_ylabel('Pre-activation variance sigma_l^2')
ax1.legend(loc='lower left', frameon=True)
ax1.grid(alpha=0.25, which='both')

epochs = [0, 1, 3, 5, 10]
ax2.axhline(0.0, color='black', ls=':', lw=1.2)
ax2.plot(epochs, [0.00, 0.02, 0.04, 0.05, 0.04], 'o-', color='#0033cc', lw=2, label='Smooth RectLU (50:50 Balance)')
ax2.plot(epochs, [0.00, -0.06, -0.09, -0.08, -0.07], '^-.', color='#800080', lw=2, label='ReLU Control (99:1 Imbalance)')
ax2.plot(epochs, [0.00, -0.22, -0.41, -0.46, -0.48], 's-', color='#cc0000', lw=2, label='Smooth RectLU (99:1 Imbalance)')
ax2.set_xlim(0, 10)
ax2.set_ylim(-0.6, 0.3)
ax2.set_xlabel('Training Epoch')
ax2.set_ylabel('Dense Pre-Act Mean mu_dense')
ax2.legend(loc='lower left', frameon=True)
ax2.grid(alpha=0.25)
plt.tight_layout()
fig.savefig('figures/fig2_variance_and_drift.pdf', dpi=300)
fig.savefig('figures/fig2_variance_and_drift.png', dpi=300)
plt.close(fig)
print('Saved 300 DPI figures in figures/')
